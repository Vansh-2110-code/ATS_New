const Review = require('../models/Review');
const User = require('../models/User');
const CallLog = require('../models/CallLog');
const Interview = require('../models/Interview');
const Candidate = require('../models/Candidate');
const { getDateRange } = require('../utils/helpers');

// Helper to calculate real recruiter metrics from DB
async function calculateRecruiterMetrics(employeeId, startDate, endDate) {
  const start = new Date(startDate);
  const end = new Date(endDate);
  end.setHours(23, 59, 59, 999);

  const empUser = await User.findById(employeeId).select('name employeeId');
  const empName = empUser ? empUser.name : '';

  // 1. Call Logs
  const actualCallsFromLogs = await CallLog.countDocuments({
    $or: [
      { recruiter: employeeId },
      { recruiterName: { $regex: empName, $options: 'i' } }
    ],
    createdAt: { $gte: start, $lte: end }
  });

  // Also check Candidate call updates
  const candCalls = await Candidate.countDocuments({
    $or: [
      { assignedRecruiter: employeeId },
      { assignedRecruiterName: { $regex: empName, $options: 'i' } }
    ],
    $or: [
      { callDate: { $gte: start, $lte: end } },
      { callingDetails: { $exists: true, $ne: '' }, updatedAt: { $gte: start, $lte: end } }
    ]
  });

  // 2. Interviews
  const actualInterviewsFromSchedule = await Interview.countDocuments({
    $or: [
      { recruiter: employeeId },
      { recruiterName: { $regex: empName, $options: 'i' } }
    ],
    date: { $gte: start, $lte: end }
  });

  const candInterviews = await Candidate.countDocuments({
    $or: [
      { assignedRecruiter: employeeId },
      { assignedRecruiterName: { $regex: empName, $options: 'i' } }
    ],
    interviewDate: { $gte: start, $lte: end }
  });

  // 3. Placements
  const actualPlacements = await Candidate.countDocuments({
    $or: [
      { assignedRecruiter: employeeId },
      { assignedRecruiterName: { $regex: empName, $options: 'i' } }
    ],
    status: { $in: ['Joined', 'Offer Accept', 'Placed'] },
    updatedAt: { $gte: start, $lte: end }
  });

  return {
    actualCalls: Math.max(actualCallsFromLogs, candCalls),
    actualInterviews: Math.max(actualInterviewsFromSchedule, candInterviews),
    actualPlacements
  };
}

// GET /api/reviews/employee-metrics — fetch live real calls and interviews for review modal (Requirement 12)
exports.getEmployeeMetrics = async (req, res, next) => {
  try {
    const { employee, startDate, endDate } = req.query;
    if (!employee || !startDate || !endDate) {
      return res.status(400).json({ message: 'employee, startDate, and endDate are required' });
    }

    const metrics = await calculateRecruiterMetrics(employee, startDate, endDate);
    res.json(metrics);
  } catch (err) {
    next(err);
  }
};

// GET /api/reviews — list reviews with automatic monthly generation for active recruiters (Requirement 13)
exports.getReviews = async (req, res, next) => {
  try {
    const { dateRange = 'month', startDate, endDate, employee } = req.query;
    const { start, end } = getDateRange(dateRange, startDate, endDate);

    const filter = {
      reviewPeriodStart: { $gte: start },
      reviewPeriodEnd: { $lte: end }
    };

    if (employee) {
      filter.employee = employee;
    }

    let reviews = await Review.find(filter)
      .populate('employee', 'name employeeId role')
      .populate('reviewer', 'name')
      .sort('-createdAt');

    // If month review requested and empty, auto-generate placeholder review entries for active recruiters
    if (reviews.length === 0 && dateRange.toLowerCase() === 'month') {
      const activeRecruiters = await User.find({
        role: { $in: ['recruiter', 'tl'] },
        status: { $ne: 'Suspended' },
        isDemoAccount: { $ne: true },
        employeeId: { $not: /^DEMO/i }
      }).select('name employeeId role').limit(20);

      const autoGenerated = [];
      for (const rec of activeRecruiters) {
        const liveMetrics = await calculateRecruiterMetrics(rec._id, start, end);
        autoGenerated.push({
          _id: `auto_${rec._id}`,
          employee: rec,
          reviewer: { name: 'System Auto-Audit' },
          reviewPeriodStart: start,
          reviewPeriodEnd: end,
          rating: liveMetrics.actualPlacements > 0 ? 4 : (liveMetrics.actualInterviews > 0 ? 3 : 2),
          comments: `Auto-computed monthly performance: ${liveMetrics.actualCalls} calls, ${liveMetrics.actualInterviews} interviews, ${liveMetrics.actualPlacements} placements.`,
          metrics: {
            targetCalls: 100,
            actualCalls: liveMetrics.actualCalls,
            targetInterviews: 10,
            actualInterviews: liveMetrics.actualInterviews,
            targetPlacements: 2,
            actualPlacements: liveMetrics.actualPlacements
          },
          isAutoGenerated: true,
          createdAt: new Date()
        });
      }
      return res.json(autoGenerated);
    }

    res.json(reviews);
  } catch (err) {
    next(err);
  }
};

exports.createReview = async (req, res, next) => {
  try {
    const { employee, reviewPeriodStart, reviewPeriodEnd, rating, comments, metrics = {} } = req.body;

    // If actuals are not provided or 0, calculate from DB (Requirement 12)
    if (!metrics.actualCalls || !metrics.actualInterviews) {
      const live = await calculateRecruiterMetrics(employee, reviewPeriodStart, reviewPeriodEnd);
      metrics.actualCalls = metrics.actualCalls || live.actualCalls;
      metrics.actualInterviews = metrics.actualInterviews || live.actualInterviews;
      metrics.actualPlacements = metrics.actualPlacements || live.actualPlacements;
    }

    const review = await Review.create({
      employee,
      reviewer: req.user._id,
      reviewPeriodStart,
      reviewPeriodEnd,
      rating,
      comments,
      metrics
    });

    res.status(201).json(review);
  } catch (err) {
    next(err);
  }
};

exports.getReview = async (req, res, next) => {
  try {
    const review = await Review.findById(req.params.id)
      .populate('employee', 'name employeeId')
      .populate('reviewer', 'name');

    if (!review) return res.status(404).json({ message: 'Review not found' });
    res.json(review);
  } catch (err) {
    next(err);
  }
};

exports.updateReview = async (req, res, next) => {
  try {
    const review = await Review.findByIdAndUpdate(req.params.id, req.body, {
      new: true,
      runValidators: true
    });
    if (!review) return res.status(404).json({ message: 'Review not found' });
    res.json(review);
  } catch (err) {
    next(err);
  }
};

exports.deleteReview = async (req, res, next) => {
  try {
    const review = await Review.findByIdAndDelete(req.params.id);
    if (!review) return res.status(404).json({ message: 'Review not found' });
    res.json({ message: 'Review deleted' });
  } catch (err) {
    next(err);
  }
};
